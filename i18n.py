def translate(language: str, key: str, **values) -> str:
    table = _TEXT.get(language, _TEXT["vi"])
    # Try dotted key first (e.g. "nav.products"), then convert to underscore (e.g. "nav_products")
    template = table.get(key)
    if template is None and "." in key:
        underscore_key = key.replace(".", "_")
        template = table.get(underscore_key)
    if template is None:
        # Fallback to Vietnamese
        vi_table = _TEXT["vi"]
        template = vi_table.get(key)
        if template is None and "." in key:
            template = vi_table.get(key.replace(".", "_"))
        if template is None:
            return key
    try:
        return template.format(**values)
    except (KeyError, IndexError):
        return template
